async function seedFoodLibrary() {
  console.log(`Starting food library seeding (${FOOD_ITEMS.length} items)...`);

  let createdCount = 0;
  let updatedCount = 0;

  for (const item of FOOD_ITEMS) {
    const existing = await prisma.foodItem.findFirst({
      where: { name: item.name, isCustom: false },
    });

    if (existing) {
      await prisma.foodItem.update({
        where: { id: existing.id },
        data: {
          category: item.category,
          description: item.description,
          caloriesPer100g: item.caloriesPer100g,
          protein: item.protein,
          carbohydrates: item.carbohydrates,
          fat: item.fat,
          defaultServingSize: item.defaultServingSize,
          defaultServingUnit: item.defaultServingUnit,
          servingWeightGrams: item.servingWeightGrams,
          isActive: true,
        },
      });
      updatedCount++;
    } else {
      await prisma.foodItem.create({
        data: {
          name: item.name,
          category: item.category,
          description: item.description,
          caloriesPer100g: item.caloriesPer100g,
          protein: item.protein,
          carbohydrates: item.carbohydrates,
          fat: item.fat,
          defaultServingSize: item.defaultServingSize,
          defaultServingUnit: item.defaultServingUnit,
          servingWeightGrams: item.servingWeightGrams,
          isCustom: false,
          isActive: true,
        },
      });
      createdCount++;
    }
  }

  console.log(`✓ Food library seeded successfully: ${createdCount} created, ${updatedCount} updated.`);
}

seedFoodLibrary()
  .catch((e) => {
    console.error("Error seeding food library:", e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });

