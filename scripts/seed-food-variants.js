async function seedVariants() {
  console.log("🌱 Seeding Smart Indian Food Variants into Neon PostgreSQL...");

  for (const item of FOODS_WITH_VARIANTS) {
    // 1. Find or create parent FoodItem
    let parent = await prisma.foodItem.findFirst({
      where: {
        OR: [
          { name: { equals: item.parentName, mode: "insensitive" } },
          { name: { contains: item.parentName.split(" ")[0], mode: "insensitive" } },
        ],
        isCustom: false,
      },
    });

    if (!parent) {
      parent = await prisma.foodItem.create({
        data: {
          name: item.parentName,
          category: item.category,
          description: item.description,
          caloriesPer100g: item.defaultCalories,
          protein: item.defaultProtein,
          carbohydrates: item.defaultCarbs,
          fat: item.defaultFat,
          defaultServingSize: 1,
          defaultServingUnit: "bowl",
          servingWeightGrams: item.servingConversions.medium_bowl,
          hasVariants: true,
          isActive: true,
        },
      });
      console.log(`Created parent food: ${parent.name}`);
    } else {
      parent = await prisma.foodItem.update({
        where: { id: parent.id },
        data: {
          hasVariants: true,
          defaultServingUnit: "bowl",
          servingWeightGrams: item.servingConversions.medium_bowl,
        },
      });
      console.log(`Updated parent food: ${parent.name} (hasVariants: true)`);
    }

    // 2. Upsert each variant
    for (const v of item.variants) {
      const existingVariant = await prisma.foodVariant.findFirst({
        where: {
          foodItemId: parent.id,
          name: v.name,
        },
      });

      if (existingVariant) {
        await prisma.foodVariant.update({
          where: { id: existingVariant.id },
          data: {
            variantType: v.variantType,
            description: v.description,
            caloriesPer100g: v.caloriesPer100g,
            protein: v.protein,
            carbohydrates: v.carbohydrates,
            fat: v.fat,
            isDefault: v.isDefault,
            servingConversions: item.servingConversions,
            preparationMethod: v.preparationMethod,
            nutritionSource: v.nutritionSource,
            confidenceLevel: v.confidenceLevel,
            displayOrder: v.displayOrder,
            isActive: true,
          },
        });
      } else {
        await prisma.foodVariant.create({
          data: {
            foodItemId: parent.id,
            name: v.name,
            variantType: v.variantType,
            description: v.description,
            caloriesPer100g: v.caloriesPer100g,
            protein: v.protein,
            carbohydrates: v.carbohydrates,
            fat: v.fat,
            isDefault: v.isDefault,
            servingConversions: item.servingConversions,
            preparationMethod: v.preparationMethod,
            nutritionSource: v.nutritionSource,
            confidenceLevel: v.confidenceLevel,
            displayOrder: v.displayOrder,
            isActive: true,
          },
        });
      }
      console.log(`  └─ Variant: ${v.name} (${v.caloriesPer100g} kcal/100g, P: ${v.protein}g)`);
    }
  }

  console.log("✅ Smart Indian Food Variants successfully seeded in Neon PostgreSQL!");
}

seedVariants()
  .catch((e) => {
    console.error("Error seeding variants:", e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
